package render

import (
	"fmt"
	"html"
	"strings"
)

// Readme returns the README that stacks the images. Each repository image is
// its own link, which is why the page is not one big picture.
func (pg Page) Readme(dir string) string {
	var b strings.Builder
	b.WriteString("<!-- Generated by cmd/generate. Change config.json or the code, not this file. -->\n\n")
	img := func(p Piece, attrs string) string {
		tag := fmt.Sprintf(`<img src="%s/%s" %s alt="%s">`, dir, p.File, attrs, html.EscapeString(p.Alt))
		if p.Link == "" {
			return tag
		}
		return fmt.Sprintf(`<a href="%s">%s</a>`, p.Link, tag)
	}

	b.WriteString(img(pg.Hero, `width="100%"`) + "\n\n")

	// The feature card floats left and the small cards flow beside it, two
	// to a row. Widths are percentages so the block scales with the page.
	if pg.Feature != nil {
		b.WriteString(img(*pg.Feature, `align="left" width="40%"`) + "\n")
	}
	for i, c := range pg.Cards {
		b.WriteString(img(c, `width="28%"`))
		if i%2 == 0 && i+1 < len(pg.Cards) {
			b.WriteString(" ")
		} else {
			b.WriteString("\n")
		}
	}
	if pg.Feature != nil {
		b.WriteString(`<br clear="left">` + "\n")
	}
	b.WriteString("\n")

	b.WriteString(img(pg.Head, `width="100%"`) + "\n")
	for _, r := range pg.Rows {
		b.WriteString(img(r, `width="100%"`) + "\n")
	}
	b.WriteString("\n<sub>Refreshed daily. Each card's chart is drawn to that repository's own scale.</sub>\n")
	return b.String()
}

// Sheet lays the pieces out the way the README does, in one image, for
// checking the result without publishing it.
func (pg Page) Sheet(th Theme, m Mode) string {
	const margin, gap = 32.0, 5.0
	bg := "#0d1117"
	if m == ModeLight {
		bg = "#ffffff"
	}
	var b strings.Builder
	y := margin
	place := func(p Piece, x, y float64) {
		fmt.Fprintf(&b, `<svg x="%s" y="%s" width="%s" height="%s" viewBox="0 0 %s %s">%s</svg>`,
			n(x), n(y), n(p.W), n(p.H), n(p.W), n(p.H), p.body)
	}
	place(pg.Hero, margin, y)
	y += pg.Hero.H + 16

	blockH := 0.0
	if pg.Feature != nil {
		place(*pg.Feature, margin, y)
		blockH = pg.Feature.H
	}
	for i, c := range pg.Cards {
		cx := margin + featureW + 20 + float64(i%2)*(cardW+4)
		cy := y + float64(i/2)*(cardH+gap)
		place(c, cx, cy)
		blockH = max(blockH, cy+cardH-y)
	}
	y += blockH + 16

	place(pg.Head, margin, y)
	y += pg.Head.H + gap
	for _, r := range pg.Rows {
		place(r, margin, y)
		y += r.H + gap
	}
	h := y + margin
	w := pageW + 2*margin
	return fmt.Sprintf(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %s %s" width="%s" height="%s">%s<rect width="100%%" height="100%%" fill="%s"/>%s</svg>`+"\n",
		n(w), n(h), n(w), n(h), style(th, m), bg, b.String())
}

// All returns every piece in page order.
func (pg Page) All() []Piece {
	out := []Piece{pg.Hero}
	if pg.Feature != nil {
		out = append(out, *pg.Feature)
	}
	out = append(out, pg.Cards...)
	out = append(out, pg.Head)
	return append(out, pg.Rows...)
}
